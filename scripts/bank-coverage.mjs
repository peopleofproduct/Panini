/**
 * Generates docs/bank-coverage.md — the public coverage matrix joining
 * bank-names.json (detectable banks) × csv-layouts.json (dedicated
 * layouts) × the corpus (regression-gated banks).
 *
 *   node scripts/bank-coverage.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FORMATS = join(ROOT, 'packages/extract/formats');

const names = JSON.parse(readFileSync(join(FORMATS, 'bank-names.json'), 'utf8'));
const layoutsFile = JSON.parse(readFileSync(join(FORMATS, 'csv-layouts.json'), 'utf8'));
const corpusFiles = readdirSync(join(FORMATS, 'corpus')).filter((f) => f.endsWith('-csv.json'));

const layoutsByBank = new Map();
for (const l of layoutsFile.layouts) {
  if (!layoutsByBank.has(l.bank)) layoutsByBank.set(l.bank, []);
  layoutsByBank.get(l.bank).push(l);
}
const corpusBanks = new Set();
for (const f of corpusFiles) {
  const fixture = JSON.parse(readFileSync(join(FORMATS, 'corpus', f), 'utf8'));
  const bank = fixture.expect?.bank;
  if (bank) corpusBanks.add(bank);
}

const rows = [];
let dedicated = 0;
for (const bank of names.banks) {
  const list = layoutsByBank.get(bank.id);
  const gated = corpusBanks.has(bank.id);
  if (list && gated) dedicated += 1;
  rows.push({
    id: bank.id,
    layoutId: list ? list.map((l) => l.id).join(', ') : null,
    gated,
  });
}

const withLayout = rows.filter((r) => r.layoutId !== null);
const nameOnly = rows.filter((r) => r.layoutId === null);
const numLayouts = layoutsFile.layouts.filter((l) => l.bank !== 'GENERIC').length;

const lines = [
  '# Bank coverage',
  '',
  '<!-- Generated by `npm run coverage:banks` — do not edit by hand. -->',
  '',
  `**${dedicated} banks** have dedicated layouts (${numLayouts} layout variants, corpus-gated). ` +
    `**${nameOnly.length} more** are name-detectable in statement preambles ` +
    '(they parse via the generic fallback and report their `bank` — a',
  'dedicated layout is a JSON entry away; see `docs/bank-layout-guide.md`).',
  'Credit-card statements (`kind: "credit_card"`) and PhonePe vertical',
  'statements parse via dedicated layouts/parsers — also corpus-gated.',
  'PDF statements use bank-agnostic column anchors and are not listed here.',
  '',
  '## Dedicated layouts',
  '',
  '| Bank | Layout | Corpus fixture |',
  '| --- | --- | --- |',
  ...withLayout.map((r) => `| ${r.id} | \`${r.layoutId}\` | ${r.gated ? 'yes' : '**missing**'} |`),
  '',
  '## Detected by name only — layout wanted',
  '',
  'These banks are recognised in statement preambles and parse via the',
  'generic fallback, but have no dedicated layout yet. Real exports make',
  'them one-JSON-entry contributions.',
  '',
  '| Bank |',
  '| --- |',
  ...nameOnly.map((r) => `| ${r.id} |`),
  '',
  'Bank not listed? A statement preamble we do not recognise reports',
  '`bank: null` and still parses generically — add the name to',
  '`packages/extract/formats/bank-names.json` alongside the layout.',
];

const out = join(ROOT, 'docs/bank-coverage.md');
writeFileSync(out, lines.join('\n') + '\n');
console.log(
  `wrote ${out}: ${dedicated} dedicated layouts, ${nameOnly.length} name-detectable banks`,
);
